#!/bin/sh
# Regenerates docs/API.md: the public surface as of v0.1.0, one package per
# section, as reported by go doc. Run via `make api`.
set -e
out=docs/API.md
{
  echo "# Twine public API"
  echo
  echo "Generated by \`make api\` from \`go doc -short\`. This is the surface"
  echo "at v0.1.0; it may still change before v1.0.0, and changes are recorded here."
  for p in . ./proto ./http ./tls; do
    name=$(go list -f '{{.ImportPath}}' $p)
    echo
    echo "## $name"
    echo
    echo '```'
    go doc -all $p | grep -E '^(func |type |var |const |    [A-Z][A-Za-z0-9_]* +[^ ]+.*// |    [A-Z][A-Za-z0-9_]*\(.*\)$)' | sed 's/[[:space:]]*$//'
    echo '```'
  done
} > $out
echo "wrote $out"
