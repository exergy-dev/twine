#!/bin/sh
# Regenerates docs/API.md: the exported surface of every public package, one
# section per package, as printed by `go doc -all` with the doc text removed
# (declarations, interface methods, struct fields, const and var blocks are
# kept). Run via `make api`; CI fails when the committed file is stale.
# API_OUT=path writes somewhere else (for a dry run); GO selects the go command.
set -e
GO=${GO:-go}
out=${API_OUT:-docs/API.md}
tag=$(git describe --tags --abbrev=0 2>/dev/null || echo none)
{
  echo "# Twine public API"
  echo
  echo "Generated by \`make api\` from \`go doc -all\` (latest release tag: $tag)."
  echo "The API may change before v1.0.0; CHANGELOG.md records what changed."
  for p in . ./proto ./http ./tls; do
    name=$($GO list -f '{{.ImportPath}}' "$p")
    echo
    echo "## $name"
    echo
    echo '```'
    # Skip the package doc (everything before the first CONSTANTS, VARIABLES,
    # FUNCTIONS or TYPES heading), print every column-0 declaration, and
    # inside a ( or { block keep the members and the closer but drop comment
    # and blank lines (except go doc's "Has unexported fields." marker). Doc
    # text is indented and never printed.
    $GO doc -all "$p" | awk '
      /^(CONSTANTS|VARIABLES|FUNCTIONS|TYPES)$/ { body = 1; next }
      !body { next }
      inblk {
        if ($0 ~ /^[)}]/) { print; inblk = 0; next }
        if ($0 ~ /Has unexported fields/) { print; next }
        if ($0 ~ /^[ \t]*\/\// || $0 ~ /^[ \t]*$/) next
        print
        next
      }
      /^(func|type|var|const) / { print; if ($0 ~ /[({]$/) inblk = 1 }
    ' | sed 's/[[:space:]]*$//'
    echo '```'
  done
} > "$out"
echo "wrote $out"
