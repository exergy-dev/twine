#!/bin/sh
# Regenerates docs/API.md: the frozen v1 public surface, one package per
# section, as reported by go doc. Run via `make api`.
set -e
out=docs/API.md
{
  echo "# Twine v1 public API"
  echo
  echo "Generated by \`make api\` from \`go doc -short\`. This is the surface frozen"
  echo "at v1.0.0: signatures may gain options but must not change shape within v1."
  for p in . ./proto ./http ./tls; do
    name=$(go list -f '{{.ImportPath}}' $p)
    echo
    echo "## $name"
    echo
    echo '```'
    go doc -all $p | grep -E '^(func |type |var |const |    [A-Z][A-Za-z0-9_]* +[^ ]+.*// |    [A-Z][A-Za-z0-9_]*\(.*\)$)' | sed 's/[[:space:]]*$//'
    echo '```'
  done
} > $out
echo "wrote $out"
