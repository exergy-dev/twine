#!/usr/bin/env python3
"""Writes docs/API.md: the public surface of the library crates, extracted from
the sources (`pub` items at module level and public methods in `impl` blocks of
public types), the Rust counterpart of the Go repo's `make api`.
Run from rust/: python3 -I scripts/apidump.py"""
import os, re, sys
CRATES = ["twine", "twine-proto", "twine-http", "twine-tls"]
ITEM = re.compile(r"^(\s*)pub (fn|struct|enum|trait|type|const|static|mod|use)\b")

def items(path):
    out, skip_depth, in_test = [], None, False
    lines = open(path).read().split("\n")
    i = 0
    while i < len(lines):
        l = lines[i]
        if l.startswith("#[cfg(test)]"):
            in_test = True
        if in_test and re.match(r"^(pub )?mod \w+", l):
            break
        # skip bodies of crate-private modules such as `pub(crate) mod flags {`
        if skip_depth is None and re.match(r"^\s*(pub\(crate\) |)mod \w+ \{", l) and "pub(crate)" in l:
            skip_depth = len(l) - len(l.lstrip())
        elif skip_depth is not None and l.startswith(" " * skip_depth + "}"):
            skip_depth = None
        elif skip_depth is None and ITEM.match(l) and "pub(crate)" not in l:
            sig = l.rstrip()
            while not re.search(r"[{;]\s*$", sig) and "where" not in sig and i + 1 < len(lines):
                i += 1
                sig += " " + lines[i].strip()
            sig = re.sub(r"\s*\{.*$", "", sig)
            sig = re.sub(r"\s*where .*$", " where ..", sig)
            sig = re.sub(r";$", "", sig)
            sig = re.sub(r"\( ", "(", re.sub(r", \)", ")", re.sub(r"\s+", " ", sig.strip())))
            indent = "    " if l.startswith(" ") else ""
            out.append(indent + sig)
        i += 1
    return out

with open("docs/API.md", "w") as f:
    f.write("# Twine (Rust) public API\n\nGenerated by `scripts/apidump.py` from the crate sources: every `pub` item\n"
            "and public method of the four library crates, one line each (signatures up to\n"
            "the opening brace). `cargo doc --workspace --no-deps --open` renders the full documentation.\n")
    for crate in CRATES:
        f.write(f"\n## {crate}\n\n```rust\n")
        for root, _, files in sorted(os.walk(f"{crate}/src")):
            for name in sorted(files):
                if not name.endswith(".rs"): continue
                path = os.path.join(root, name)
                its = items(path)
                if its:
                    f.write(f"// {path}\n" + "\n".join(its) + "\n")
        f.write("```\n")
print("wrote docs/API.md")
